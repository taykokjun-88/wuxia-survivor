def main():
    dry = "--dry" in sys.argv
    total = 0
    for f in FILES:
        p = pathlib.Path(f)
        s = p.read_text(encoding="utf-8")
        o = s
        for a, b in RENAMES:
            s = s.replace(a, b)
        if s != o:
            n = sum(o.count(a) for a, _ in RENAMES)
            total += n
            print(f"{p.relative_to(ROOT)}: {n}")
            if not dry:
                p.write_text(s, encoding="utf-8")
    print("合计替换", total)


if __name__ == "__main__":
    main()
